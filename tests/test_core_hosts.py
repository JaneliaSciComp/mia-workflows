"""mia_core.hosts: generating mia's csub policy from the base policy and the approved hosts."""

from __future__ import annotations

import json
import re
import threading
import tomllib
from pathlib import Path

import pytest

from mia_core import hosts as hosts_module
from mia_core.hosts import (
    APPROVALS_NAME,
    POLICY_NAME,
    PolicyError,
    allowed_patterns,
    approve_hosts,
    approved_hosts,
    generate_policy,
)

BASE = r"""[broker]
allowed_hosts = ["zenodo.org", "*.huggingface.co"]
note = 'a "quoted" back\slash'
port = 8080
ratio = 0.5
strict = true

[agents]
claude = ["claude", "--print"]

[limits]
jobs = 4
share = 0.25

[queues.short]
slots = 2
gpu = false
"""


@pytest.fixture(autouse=True)
def home(tmp_path, monkeypatch) -> Path:
    monkeypatch.setenv("HOME", str(tmp_path))
    return tmp_path


@pytest.fixture
def base(tmp_path) -> Path:
    path = tmp_path / "operator" / "broker.toml"
    path.parent.mkdir()
    path.write_text(BASE)
    return path


@pytest.fixture
def policy_dir(tmp_path) -> Path:
    return tmp_path / "state" / "csub"


def approve(base: Path, policy_dir: Path, hosts: list[str], **kwargs) -> list[str]:
    return approve_hosts(base, policy_dir, hosts, by="tester", kind="data", number=1, **kwargs)


def test_with_no_approvals_the_generated_policy_equals_the_base(base, policy_dir):
    generated = generate_policy(base, policy_dir)
    assert tomllib.loads(generated.read_text()) == tomllib.loads(BASE)
    assert generated.read_text().startswith(f"# Generated by mia from {base}; edits are overwritten.\n")


def test_approved_hosts_are_added_in_order_and_every_base_key_is_kept(base, policy_dir):
    approve(base, policy_dir, ["b.example.org"])
    approve(base, policy_dir, ["a.example.org"])
    expected = tomllib.loads(BASE)
    expected["broker"]["allowed_hosts"] += ["b.example.org", "a.example.org"]
    assert tomllib.loads((policy_dir / POLICY_NAME).read_text()) == expected
    assert allowed_patterns(policy_dir) == expected["broker"]["allowed_hosts"]


def test_a_host_the_base_matches_by_pattern_is_not_added(base, policy_dir):
    approve(base, policy_dir, ["cdn.huggingface.co"])
    assert allowed_patterns(policy_dir) == ["zenodo.org", "*.huggingface.co"]


@pytest.mark.parametrize("operation", ["generate", "approve"])
def test_a_base_that_is_a_symlink_inside_the_policy_dir_is_refused(tmp_path, operation):
    real = tmp_path / "shared" / "real.toml"
    real.parent.mkdir()
    real.write_text(BASE)
    directory = tmp_path / "state" / "csub"
    directory.mkdir(parents=True)
    link = directory / POLICY_NAME
    link.symlink_to(real)
    with pytest.raises(PolicyError):
        if operation == "generate":
            generate_policy(link, directory)
        else:
            approve(link, directory, ["a.example.org"])
    assert link.is_symlink()
    assert real.read_text() == BASE
    assert [path.name for path in directory.iterdir()] == [POLICY_NAME]


@pytest.mark.parametrize(
    "host", ["*.example.org", "Data.Example.org", "data.example.org.", "data.example.org:443", "10.1.2.3", "::1"]
)
def test_an_unapprovable_host_is_refused_before_anything_is_written(base, policy_dir, host):
    with pytest.raises(PolicyError, match=re.escape(host)):
        approve(base, policy_dir, [host])
    assert not (policy_dir / APPROVALS_NAME).exists()
    assert generate_policy(base, policy_dir).exists()


@pytest.mark.parametrize("through_symlink", [False, True])
@pytest.mark.parametrize("operation", ["generate", "approve"])
def test_a_policy_dir_that_holds_the_base_is_refused_and_the_base_keeps_its_bytes(
    base, tmp_path, through_symlink, operation
):
    target = base.parent
    if through_symlink:
        target = tmp_path / "link"
        target.symlink_to(base.parent)
    before = sorted(path.name for path in base.parent.iterdir())
    with pytest.raises(PolicyError):
        if operation == "generate":
            generate_policy(base, target)
        else:
            approve(base, target, ["a.example.org"])
    assert base.read_text() == BASE
    assert sorted(path.name for path in base.parent.iterdir()) == before


@pytest.mark.parametrize("operation", ["generate", "approve"])
def test_a_policy_dir_outside_home_or_inside_a_writable_mount_is_refused(base, tmp_path, monkeypatch, operation):
    home_dir = tmp_path / "home"
    home_dir.mkdir()
    monkeypatch.setenv("HOME", str(home_dir))
    outside = tmp_path / "elsewhere" / "csub"
    mount = home_dir / "mount"
    inside = mount / "csub"
    holder = home_dir / "holder"
    inner_mount = holder / "bound"
    cases = [(outside, []), (inside, [mount]), (holder, [inner_mount])]
    for directory, writable in cases:
        with pytest.raises(PolicyError, match=str(directory)):
            if operation == "generate":
                generate_policy(base, directory, writable)
            else:
                approve(base, directory, ["a.example.org"], writable=writable)
        assert not directory.exists()


def test_a_missing_or_invalid_base_is_an_error_and_writes_nothing(base, policy_dir, tmp_path):
    generate_policy(base, policy_dir)
    before = (policy_dir / POLICY_NAME).read_bytes()
    missing = tmp_path / "operator" / "absent.toml"
    with pytest.raises(PolicyError, match=str(missing)):
        generate_policy(missing, policy_dir)
    broken = tmp_path / "operator" / "broken.toml"
    broken.write_text("not = = toml")
    with pytest.raises(PolicyError, match=str(broken)):
        generate_policy(broken, policy_dir)
    assert (policy_dir / POLICY_NAME).read_bytes() == before


def test_a_value_the_writer_cannot_write_names_its_key(tmp_path, policy_dir):
    odd = tmp_path / "operator" / "odd.toml"
    odd.parent.mkdir()
    odd.write_text("[limits]\nwhen = 2026-01-01\n")
    with pytest.raises(PolicyError, match=r"limits\.when"):
        generate_policy(odd, policy_dir)
    assert not (policy_dir / POLICY_NAME).exists()


def test_an_approval_is_recorded_once(base, policy_dir):
    assert approve(base, policy_dir, ["a.example.org", "a.example.org"]) == ["a.example.org"]
    assert approve(base, policy_dir, ["a.example.org"]) == []
    lines = (policy_dir / APPROVALS_NAME).read_text().splitlines()
    assert len(lines) == 1
    record = json.loads(lines[0])
    assert (record["host"], record["by"], record["kind"], record["number"]) == ("a.example.org", "tester", "data", 1)
    assert record["at"]


def test_a_broken_approvals_line_names_the_file_and_line(base, policy_dir):
    policy_dir.mkdir(parents=True)
    (policy_dir / APPROVALS_NAME).write_text('{"host": "a.example.org"}\nnot json\n')
    with pytest.raises(PolicyError, match=r"approved-hosts\.jsonl line 2"):
        approved_hosts(policy_dir)


def test_a_base_that_cannot_be_read_records_no_approval(tmp_path, policy_dir):
    with pytest.raises(PolicyError):
        approve(tmp_path / "operator" / "absent.toml", policy_dir, ["a.example.org"])
    assert not (policy_dir / APPROVALS_NAME).exists()


def run_threads(target, count: int = 20) -> list[BaseException]:
    errors: list[BaseException] = []

    def guarded(index: int) -> None:
        try:
            target(index)
        except BaseException as error:  # noqa: BLE001 - collected and asserted empty by the caller
            errors.append(error)

    threads = [threading.Thread(target=guarded, args=(index,)) for index in range(count)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    return errors


def test_approvals_from_many_threads_all_land_in_the_policy(base, policy_dir):
    names = [f"h{index}.example.org" for index in range(20)]
    assert run_threads(lambda index: approve(base, policy_dir, [names[index]])) == []
    assert len((policy_dir / APPROVALS_NAME).read_text().splitlines()) == 20
    assert set(names) <= set(allowed_patterns(policy_dir))


def test_generations_at_once_never_fail_and_never_publish_a_partial_file(base, policy_dir):
    assert run_threads(lambda index: generate_policy(base, policy_dir)) == []
    assert tomllib.loads((policy_dir / POLICY_NAME).read_text()) == tomllib.loads(BASE)
    assert [path.name for path in policy_dir.iterdir()] == [POLICY_NAME]


def test_a_generation_that_read_older_approvals_catches_up(base, policy_dir, monkeypatch):
    policy_dir.mkdir(parents=True)
    real_dump = hosts_module.dump_toml
    calls: list[int] = []

    def dump_after_a_late_approval(data: dict) -> str:
        if not calls:
            with (policy_dir / APPROVALS_NAME).open("a") as approvals:
                approvals.write(json.dumps({"host": "late.example.org"}) + "\n")
        calls.append(1)
        return real_dump(data)

    monkeypatch.setattr(hosts_module, "dump_toml", dump_after_a_late_approval)
    generate_policy(base, policy_dir)
    assert "late.example.org" in allowed_patterns(policy_dir)
